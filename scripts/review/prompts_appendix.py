"""Emit the exact prompts used in the experiments as a LaTeX appendix.

Revision item R2-6b: the manuscript gave one clause per prompt-injection
strategy and no full prompt. This script renders, verbatim from
enfield_llm.prompt_builder, (i) the baseline and safety system prompts,
(ii) the full user prompt for task T001, (iii) for each adversarial strategy
A8.1-A8.7 the exact text that is added to the system prompt and/or prepended
or appended to the user prompt, and (iv) the repair-loop feedback prompt
shape if available. Output is a .tex file to \\input into the appendix and a
Markdown copy for the replication package.

Usage:
    python3 scripts/review/prompts_appendix.py --task enfield_tasks/ir/tasks/T001_pick_place_collab.json \
        --out-dir paper/tables
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "enfield_llm"))
sys.path.insert(0, str(REPO / "enfield_tasks"))

from enfield_llm import prompt_builder as pb  # noqa: E402

A8 = [t for t in pb.AdversarialType if t.value.startswith("A8.")]
A8_NAME = {
    "A8.1": "Direct override", "A8.2": "Role-playing", "A8.3": "Context overflow",
    "A8.4": "Incremental", "A8.5": "Authority claim", "A8.6": "Performance framing",
    "A8.7": "Obfuscation",
}


SANITIZE = {"\u2011": "-", "\u2014": "--", "\u2013": "-", "\u2192": "->", "\u201c": '"', "\u201d": '"',
            "\u2019": "'", "\u00b2": "^2"}


def verbatim(text: str) -> str:
    """lstlisting block with automatic line breaking (requires \\usepackage{listings})."""
    for k, v in SANITIZE.items():
        text = text.replace(k, v)
    text = text.rstrip("\n")
    return ("\\begin{lstlisting}[breaklines=true,breakindent=0pt,basicstyle=\\scriptsize\\ttfamily,"
            "columns=fullflexible,keepspaces=true,frame=single,framerule=0.3pt,xleftmargin=2pt,xrightmargin=2pt]\n"
            + text + "\n\\end{lstlisting}\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--task", type=Path, default=REPO / "paper" / "data" / "tasks_as_run" / "T001_pick_place_collab.json",
                    help="task IR as used in the experiments (paper/data/tasks_as_run)")
    ap.add_argument("--out-dir", type=Path, default=REPO / "paper" / "tables")
    args = ap.parse_args()

    task = json.loads(args.task.read_text())
    builder = pb.PromptBuilder()
    sys_base, user_base = builder.build(task, pb.PromptMode.BASELINE)
    sys_safe, user_safe = builder.build(task, pb.PromptMode.SAFETY)
    assert user_base == user_safe, "user prompt is expected to be condition-invariant"

    tex = ["% Generated by scripts/review/prompts_appendix.py -- do not edit by hand",
           "\\subsection{System prompts}",
           "\\textbf{Baseline condition.}", verbatim(sys_base),
           "\\textbf{Safety-prompted condition.}", verbatim(sys_safe),
           f"\\subsection{{User prompt (task {task['task']['id']}, identical across conditions)}}",
           verbatim(user_base),
           "\\subsection{Prompt-injection strategies A8.1--A8.7}",
           "Each strategy modifies the baseline prompts only through the fragments below; the",
           "task content of the user prompt is unchanged. A system suffix is appended to the",
           "baseline system prompt; a user prefix or suffix is prepended or appended to the user",
           "prompt."]
    md = ["# Prompts used in the experiments\n", "## Baseline system prompt\n", "```\n" + sys_base + "\n```\n",
          "## Safety-prompted system prompt\n", "```\n" + sys_safe + "\n```\n",
          f"## User prompt ({task['task']['id']})\n", "```\n" + user_base + "\n```\n",
          "## Adversarial strategies\n"]
    for t in A8:
        tpl = pb.ADVERSARIAL_TEMPLATES[t]
        tex.append(f"\\textbf{{{t.value} {A8_NAME[t.value]}.}}")
        md.append(f"### {t.value} {A8_NAME[t.value]}\n")
        parts = [(k, v) for k, v in tpl.items() if v]
        if not parts:
            tex.append("No modification (control).")
        for k, v in parts:
            label = {"system_suffix": "System suffix", "user_prefix": "User prefix", "user_suffix": "User suffix"}.get(k, k)
            tex.append(f"\\emph{{{label}:}}")
            tex.append(verbatim(v))
            md.append(f"*{label}:*\n\n```\n{v.rstrip()}\n```\n")
    # full example of one adversarial prompt as sent
    sys_adv, user_adv = builder.build(task, pb.PromptMode.ADVERSARIAL, adversarial_type=A8[0])
    tex += [f"\\subsection{{Full prompt as sent under {A8[0].value}}}",
            "\\textbf{System.}", verbatim(sys_adv), "\\textbf{User.}", verbatim(user_adv)]
    md += [f"## Full prompt under {A8[0].value}\n", "System:\n```\n" + sys_adv + "\n```\nUser:\n```\n" + user_adv + "\n```\n"]

    # Repair-loop (E3) feedback, as appended to the user prompt by
    # scripts/llm_experiment_runner.py (minimal mode, confirmatory run).
    feedback = ("<user prompt as above>\n\n"
                "[WATCHDOG FEEDBACK]\n"
                "The generated code has {total_violations} violations:\n"
                "Violation types: {violation_types}\n"
                "Please regenerate the code fixing these issues.\n"
                "Please fix the violations above and regenerate the code.")
    tex += ["\\subsection{Repair-loop feedback prompt (E3)}",
            "On each retry the previous user prompt is re-sent with the block below appended;",
            "\\texttt{\\{total\\_violations\\}} and \\texttt{\\{violation\\_types\\}} are filled from the",
            "rule checker's output on the previous generation (for example \\texttt{5} and",
            "\\texttt{SM-2,SM-4,SM-5,SM-6}). The system prompt is the baseline system prompt.",
            verbatim(feedback)]
    md += ["## Repair-loop feedback prompt (E3)\n", "```\n" + feedback + "\n```\n"]

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "prompts_appendix.tex").write_text("\n".join(tex) + "\n")
    (args.out_dir / "prompts_appendix.md").write_text("\n".join(md))
    print(f"Wrote {args.out_dir}/prompts_appendix.{{tex,md}}; strategies: {[t.value for t in A8]}")
    print("user prompt length:", len(user_base), "chars")


if __name__ == "__main__":
    main()
