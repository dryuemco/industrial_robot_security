HEADER = "% Generated by analysis/round3/s09_tables.py -- do not edit by hand"
SHORT = {"Qwen2.5-Coder-32B": "Qwen", "DeepSeek-Coder-V2-16B": "DeepSeek", "CodeLlama-34B": "CodeLlama"}
COND_LABEL = {"baseline": "Baseline", "safety": "Safety-prompted"}


def fmt_p(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


# ----------------------------------------------------------------------------- Table 13

RULESET_ORDER = ["preregistered", "corrected-SM5", "high-precision", "high-prec+corr", "drop-SM4", "SM6-only", "SM2+SM6"]


def table13() -> str:
    t = pd.read_csv(OUT / "a1" / "table13_with_translator.csv")
    llm = "LLM baseline (E1, run 2)"
    lines = [
        HEADER,
        "\\begin{table}[t]",
        "\\caption{Sensitivity of the headline rates to the rule set and the validity gate,",
        "E1 baseline (130 stored outputs of the 135 generations), re-scored offline from the stored outputs.",
        "\\emph{Lexical} is the registered gate; \\emph{structural} additionally requires a",
        "\\texttt{def}\\ldots\\texttt{end} body, at least two distinct URScript calls and no",
        "non-URScript motion primitive. \\emph{High-precision} keeps only the three checks the",
        "first audit rated at or above 90\\% precision; \\emph{SM6-only} and \\emph{SM2+SM6} keep the",
        "checks rated at or above 90\\% by rater B and by the adjudicated labels of the second",
        "audit; \\emph{corrected SM-5} reads",
        "\\texttt{movej} velocities as joint speeds and applies the task's cap. Pass is the number",
        "of outputs admitted by the gate, Viol.\\ the violation rate among them, Safe the number of",
        "substantive-safe outputs over the 130 stored outputs, Mean the mean firings per admitted output.",
        "The last two columns score the 15 reference translations of \\ref{sec:task-ir} without",
        "(min.) and with (pre.) the \\texttt{set\\_tcp}/\\texttt{set\\_payload} preamble; all 15 pass",
        "both gates, Flagged is the number of the 15 with at least one firing and Mean the mean",
        "firings per program.}",
        "\\label{tab:sensitivity}",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.5pt}",
        "\\begin{tabular}{@{}llrrrrrr@{}}",
        "\\toprule",
        " & & \\multicolumn{4}{c}{Generated code} & \\multicolumn{2}{c}{Reference, min.\\ / pre.} \\\\",
        "\\cmidrule(lr){3-6}\\cmidrule(lr){7-8}",
        "Gate & Rule set & Pass & Viol. (\\%) & Safe & Mean & Flagged & Mean \\\\",
        "\\midrule",
    ]
    for gate in ("lexical", "structural"):
        for rs in RULESET_ORDER:
            r = t[(t["set"] == llm) & (t.gate == gate) & (t.rules == rs)].iloc[0]
            mn = t[(t["set"] == "Translator") & (t.gate == gate) & (t.rules == rs)].iloc[0]
            pr = t[(t["set"] == "Translator + preamble") & (t.gate == gate) & (t.rules == rs)].iloc[0]
            flagged = f"{int(round(mn.viol_pct * mn.gate_pass / 100))} / {int(round(pr.viol_pct * pr.gate_pass / 100))}"
            lines.append(f"{gate} & {rs} & {int(r.gate_pass)} & {r.viol_pct:.1f} & {r.safe_str} & {r['mean']:.1f} & "
                         f"{flagged} & {mn['mean']:.1f} / {pr['mean']:.1f} \\\\")
        if gate == "lexical":
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


# ----------------------------------------------------------------------------- Table 10

RULE_LABEL = {"SM-1": "Input-validation proxy (CWE-20)", "SM-2": "Error-handling proxy (CWE-252)",
              "SM-4": "Unusual conditions (CWE-754)", "SM-5": "Hardcoded value (CWE-798)",
              "SM-6": "Safety preamble", "pooled": "\\textit{Pooled}"}


def table10() -> str:
    p = pd.read_csv(OUT / "a4" / "precision.csv")
    assert (p.adj_equals_A_items == p.n).all()
    lines = [
        HEADER,
        "\\begin{table*}[t]",
        "\\caption{Second precision audit of the rule checker on gate-passing generated code",
        "(E1 and E2): 100 firings, 20 per firing check, drawn with a fixed seed and labelled",
        "independently by two raters blind to each other's labels (A: a consensus label of two",
        "authors; B: not an author, had not seen the manuscript, the rule code or the first",
        "audit). Rater B is the primary estimate. The adjudicated label, assigned by the two",
        "rater A authors in a recorded resolution of every disagreement under the written rater",
        "guide, equals rater A's label on all 100 items and is reported as a sensitivity analysis.",
        "Precision is the share of audited firings judged genuine, with Clopper-Pearson 95\\%",
        "intervals; Agree is percent agreement and $\\kappa$ Cohen's kappa between the two raters",
        "on the TP/FP decisions. The two checks that never fire (SM-3, SM-7) are not represented.}",
        "\\label{tab:precision2}",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lrrlrlrr@{}}",
        "\\toprule",
        "Check & $n$ & \\multicolumn{2}{c}{Rater B (primary)} & \\multicolumn{2}{c}{Rater A = adjudicated (sensitivity)} & Agree & $\\kappa$ \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
        " & & TP & Prec. [CI] & TP & Prec. [CI] & & \\\\",
        "\\midrule",
    ]
    order = ["SM-1", "SM-2", "SM-4", "SM-5", "SM-6", "pooled"]
    for rule in order:
        r = p[p.rule == rule].iloc[0]
        if rule == "pooled":
            lines.append("\\midrule")
        lines.append(f"{RULE_LABEL[rule]} & {int(r.n)} & {int(r.tp_B)} & {100 * r.prec_B:.1f} "
                     f"[{100 * r.cp_lo_B:.1f}, {100 * r.cp_hi_B:.1f}] & {int(r.tp_adj)} & {100 * r.prec_adj:.1f} "
                     f"[{100 * r.cp_lo_adj:.1f}, {100 * r.cp_hi_adj:.1f}] & {100 * r.agree_A_B:.0f}\\% & {r.kappa_A_B:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


# ----------------------------------------------------------------------------- per-rule means (A3)

def comparator_rules() -> str:
    m = pd.read_csv(OUT / "a3" / "per_rule_means.csv")
    m = m[m.model.isin(["pooled", "-"])]
    sets = {"llm": "LLM baseline (E1, run 2, gate-passing)", "min": "Translator", "pre": "Translator + preamble"}

    def row(basis):
        return {k: m[(m["set"] == v) & (m.basis == basis)].iloc[0] for k, v in sets.items()}

    lines = [
        HEADER,
        "\\begin{table}[t]",
        "\\caption{Mean firings per program by check: the 83 gate-passing baseline generations",
        "(LLM) against the 15 reference translations without (Ref.) and with (Ref.+pre) the",
        "\\texttt{set\\_tcp}/\\texttt{set\\_payload} preamble, and the differences. SM-3 and SM-7",
        "fire on none of these programs. The corrected rows replace only the hardcoded-value",
        "check (SM-5) with its corrected reading.}",
        "\\label{tab:perrule-mean}",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrrrr@{}}",
        "\\toprule",
        "Check & LLM & Ref. & Ref.+pre & LLM$-$Ref. & LLM$-$Ref.+pre \\\\",
        "\\midrule",
        "\\multicolumn{6}{@{}l}{\\textit{Preregistered rule set}} \\\\",
    ]
    pre = row("preregistered")
    for rule in ["SM-1", "SM-2", "SM-4", "SM-5", "SM-6"]:
        a, b, c = pre["llm"][rule], pre["min"][rule], pre["pre"][rule]
        lines.append(f"{rule} & {a:.2f} & {b:.2f} & {c:.2f} & {a - b:+.2f} & {a - c:+.2f} \\\\")
    a, b, c = pre["llm"].total, pre["min"].total, pre["pre"].total
    lines.append(f"Total & {a:.2f} & {b:.2f} & {c:.2f} & {a - b:+.2f} & {a - c:+.2f} \\\\")
    cor = row("corrected-SM5")
    lines += ["\\addlinespace", "\\multicolumn{6}{@{}l}{\\textit{With the corrected SM-5}} \\\\"]
    a, b, c = cor["llm"]["SM-5"], cor["min"]["SM-5"], cor["pre"]["SM-5"]
    lines.append(f"SM-5, corrected & {a:.2f} & {b:.2f} & {c:.2f} & {a - b:+.2f} & {a - c:+.2f} \\\\")
    a, b, c = cor["llm"].total, cor["min"].total, cor["pre"].total
    lines.append(f"Total & {a:.2f} & {b:.2f} & {c:.2f} & {a - b:+.2f} & {a - c:+.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines).replace("+0.00", "0.00").replace("-0.00", "0.00").replace(" -", " $-$")


# ----------------------------------------------------------------------------- Table 16

def _cells(r) -> str:
    if r is None or math.isnan(r.Q):
        tasks = "" if r is None else f"{int(r.tasks_in_test)}"
        return f"{tasks} & \\multicolumn{{2}}{{c}}{{undefined}}"
    return f"{int(r.tasks_in_test)} & {r.Q:.2f} & {fmt_p(r.p_exact)}"


def table16() -> str:
    pm = pd.read_csv(TABLES / "quantization_summary.csv")
    cq = pd.read_csv(OUT / "a2" / "cochran_all.csv")
    cq = cq[cq.run == "run2"]
    served = {"Qwen2.5-Coder-32B": "Q4\\_K\\_M", "DeepSeek-Coder-V2-16B": "Q4\\_0", "CodeLlama-34B": "Q4\\_0"}
    lines = [
        HEADER,
        "\\begin{table*}[t]",
        "\\caption{Quantization control. Each of the three models was re-run after the review at",
        "the quantization level it was \\emph{not} served at in the confirmatory run (Q4\\_K\\_M for",
        "the two models served at Q4\\_0 and Q4\\_0 for the model served at Q4\\_K\\_M), on the same",
        "fifteen tasks, two conditions, three repetitions, prompts, decoding settings and frozen",
        "task set, on a local RTX~5090. Gate is the number of the 45 outputs per condition that",
        "pass the validity gate; violation rate and mean count are on the gate-passing basis.",
        "Agree is the number of the 15 task cells whose binary verdict (any repetition violating)",
        "is the same at both levels; McNemar is the exact test on discordant cells and Wilcoxon",
        "the signed-rank test on per-cell mean counts. Served at gives the level of the",
        "confirmatory run. The lower block gives the cross-model Cochran $Q$ of \\ref{sec:res-sens}",
        "at the served levels and with all three models at one level, on three bases: naive (a",
        "task cell is violating when any repetition violates, with invalid outputs counted as",
        "non-violating), gate-passing (a cell is violating when any gate-passing repetition",
        "violates; a task enters only when every model has a gate-passing output) and the",
        "gate-pass indicator (a cell is 1 when any repetition passes the validity gate). Tasks is",
        "the number of task cells in the test; a test in which no task is discordant is",
        "undefined. The $p$ values are exact permutation $p$ values, uncorrected. Naive rates are",
        "the per-task violation rates of Qwen2.5-Coder-32B, DeepSeek-Coder-V2-16B and",
        "CodeLlama-34B in percent.}",
        "\\label{tab:quant}",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{@{}llrrrrrrrrrr@{}}",
        "\\toprule",
        " & & \\multicolumn{3}{c}{Q4\\_K\\_M} & \\multicolumn{3}{c}{Q4\\_0} & & & & \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
        "Model & Condition & Gate & Viol.\\ \\% & Mean & Gate & Viol.\\ \\% & Mean & Agree & McNemar $p$ & Wilcoxon $p$ & Served at \\\\",
        "\\midrule",
    ]
    for _, r in pm.iterrows():
        lines.append(
            f"{r.model if r.condition == 'baseline' else ''} & {COND_LABEL[r.condition]} & "
            f"{r['Q4_K_M_gate']:.0f} & {100 * r['Q4_K_M_viol']:.0f} & {r['Q4_K_M_mean']:.2f} & "
            f"{r['Q4_0_gate']:.0f} & {100 * r['Q4_0_viol']:.0f} & {r['Q4_0_mean']:.2f} & "
            f"{r.agree:.0f}/{r.cells:.0f} & {r.mcnemar_p:.2f} & {r.wilcoxon_p:.3f} & "
            f"{served[r.model] if r.condition == 'baseline' else ''} \\\\")
        if r.condition == "safety":
            lines.append("\\addlinespace")
    lines += [
        "\\midrule",
        "\\multicolumn{12}{@{}l}{\\textit{Cross-model Cochran $Q$ over the 15 task cells}} \\\\",
        " & & \\multicolumn{3}{c}{Naive} & \\multicolumn{3}{c}{Gate-passing} & \\multicolumn{3}{c}{Gate-pass indicator} & \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\\cmidrule(lr){9-11}",
        "Levels & Condition & Tasks & $Q$ & $p$ & Tasks & $Q$ & $p$ & Tasks & $Q$ & $p$ & Naive rates \\\\",
        "\\midrule",
    ]
    names = {"as served (Q4_K_M / Q4_0 / Q4_0)": "As served", "all Q4_K_M": "All Q4\\_K\\_M", "all Q4_0": "All Q4\\_0"}
    for variant, label in names.items():
        for cond in ("baseline", "safety"):
            g = cq[(cq.variant == variant) & (cq.condition == cond)].set_index("basis")
            nv = g.loc["naive"]
            rates = "/".join(f"{100 * nv[f'rate_{m}']:.0f}" for m in MODELS)
            lines.append(f"{label if cond == 'baseline' else ''} & {COND_LABEL[cond]} & {_cells(nv)} & "
                         f"{_cells(g.loc['gate-passing'])} & {_cells(g.loc['gate-pass'])} & {rates} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


# ----------------------------------------------------------------------------- registered cross-model tests

STRATEGY = {"A8.1": "Direct override", "A8.2": "Role playing", "A8.3": "Context overflow", "A8.4": "Incremental escalation",
            "A8.5": "Authority claim", "A8.6": "Performance framing", "A8.7": "Obfuscation"}


def crossmodel_registered() -> str:
    four = pd.read_csv(OUT / "f1" / "f4_cochran_four_conditions.csv")
    subs = pd.read_csv(OUT / "f1" / "f4_cochran_adversarial_subtypes.csv")
    four, subs = four[four.run == "run2"], subs[subs.run == "run2"]
    rows = [("Baseline (neutral prompt)", four[four.condition == "baseline"]),
            ("Safety-prompted", four[four.condition == "safety"])]
    rows += [(f"{k} {v}", subs[subs.condition == f"adversarial_{k}"]) for k, v in STRATEGY.items()]
    rows.append(("Repair loop, final attempt", four[four.condition == "watchdog"]))
    rate_cols = ["rate_qwen2.5-coder:32b", "rate_deepseek-coder-v2:16b", "rate_codellama:34b"]
    lines = [
        HEADER,
        "\\begin{table*}[t]",
        "\\caption{Every cross-model Cochran $Q$ test registered in the first preregistration",
        "amendment: one test per prompt condition across the three models, as an exploratory",
        "analysis reported with an uncorrected $p$ value. The registered conditions are the",
        "baseline and safety-prompted conditions of E1, each prompt-injection strategy of E2",
        "(one repetition per cell) and the repair loop of E3, scored at its final attempt. The",
        "three bases are those of Table~\\ref{tab:quant}: naive, gate-passing and the gate-pass",
        "indicator. Tasks is the number of task cells in the test; a test in which no task is",
        "discordant is undefined. The $p$ values are exact permutation $p$ values, uncorrected.",
        "Naive rates are the per-task violation rates of Qwen2.5-Coder-32B, DeepSeek-Coder-V2-16B",
        "and CodeLlama-34B in percent. Run 1 gives the same values on every line.}",
        "\\label{tab:crossmodel}",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrrrrrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Naive} & \\multicolumn{3}{c}{Gate-passing} & \\multicolumn{3}{c}{Gate-pass indicator} & \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}",
        "Condition & Tasks & $Q$ & $p$ & Tasks & $Q$ & $p$ & Tasks & $Q$ & $p$ & Naive rates \\\\",
        "\\midrule",
    ]
    for label, g in rows:
        g = g.set_index("basis")
        nv = g.loc["naive"]
        rates = "/".join(f"{100 * nv[c]:.0f}" for c in rate_cols)
        lines.append(f"{label} & {_cells(nv)} & {_cells(g.loc['gate-passing'])} & {_cells(g.loc['gate-pass'])} & {rates} \\\\")
        if label.startswith("Safety") or label.startswith("A8.7"):
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out-dir", type=Path, default=TABLES)
    args = ap.parse_args()
    files = {"sensitivity_e1_baseline.tex": table13(), "precision_audit_v2.tex": table10(),
             "comparator_rules.tex": comparator_rules(), "quantization_summary.tex": table16(),
             "crossmodel_registered.tex": crossmodel_registered()}
    for name, text in files.items():
        (args.out_dir / name).write_text(text)
        print(f"wrote {args.out_dir / name}")


if __name__ == "__main__":
    main()
